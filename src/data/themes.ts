import type { DialogueLine, Level, Phrase, Question, Theme, VocabItem } from './types'

type V = [pt: string, fr: string, ex?: string, exFr?: string, note?: string]
type L = [speaker: string, pt: string, fr: string]
type P = [pt: string, fr: string, tip?: string]

interface ThemeSource {
  id: string
  title: string
  ptTitle: string
  level: Level
  emoji: string
  description: string
  vocab: V[]
  dialogueTitle: string
  lines: L[]
  questions: Question[]
  phrases: P[]
}

const build = (t: ThemeSource): Theme => ({
  id: t.id,
  title: t.title,
  ptTitle: t.ptTitle,
  level: t.level,
  emoji: t.emoji,
  description: t.description,
  vocab: t.vocab.map(
    ([pt, fr, ex, exFr, note], i): VocabItem => ({ id: `${t.id}-v${i}`, pt, fr, ex, exFr, note }),
  ),
  dialogue: {
    title: t.dialogueTitle,
    lines: t.lines.map(([speaker, pt, fr]): DialogueLine => ({ speaker, pt, fr })),
  },
  questions: t.questions,
  phrases: t.phrases.map(([pt, fr, tip], i): Phrase => ({ id: `${t.id}-p${i}`, pt, fr, tip })),
})

